import evaluate

class RAGEvaluator:
    def __init__(self):
        """
        Initializes the evaluator by loading the necessary Hugging Face evaluate modules.
        Make sure you have installed: pip install evaluate rouge_score sacrebleu
        """
        print("Loading evaluation metrics...")
        self.bleu_metric = evaluate.load("sacrebleu")
        self.rouge_metric = evaluate.load("rouge")

    def compute_metrics(self, predictions: list[str], references: list[str]) -> dict:
        """
        Computes the BLEU and ROUGE scores.
        
        Args:
            predictions (list[str]): The responses generated by the model (BlossomBot).
            references (list[str]): The ideal responses (Ground Truth).
            
        Returns:
            dict: Dictionary with the aggregated scores.
        """
        if not predictions or not references:
            raise ValueError("The prediction and reference lists cannot be empty.")

        bleu_result = self.bleu_metric.compute(predictions=predictions, references=references)
        rouge_result = self.rouge_metric.compute(predictions=predictions, references=references)
        
        return {
            "bleu": bleu_result["score"],
            "rouge1": rouge_result["rouge1"],
            "rouge2": rouge_result["rouge2"],
            "rougeL": rouge_result["rougeL"]
        }

    def display_results(self, results: dict):
        """
        Displays the evaluation results in a clean format in the console/notebook.
        """
        print("\nNLP METRICS EVALUATION (BlossomBot)")
        print("-" * 50)
        print(f" BLEU Score: {results.get('bleu', 0):.2f}")
        print(f" ROUGE-1:    {results.get('rouge1', 0):.4f}")
        print(f" ROUGE-2:    {results.get('rouge2', 0):.4f}")
        print(f" ROUGE-L:    {results.get('rougeL', 0):.4f}")
        print("-" * 50)